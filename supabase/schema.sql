alter table teacher_hub.categories enable row level security;
alter table teacher_hub.documents enable row level security;
alter table teacher_hub.document_categories enable row level security;
alter table teacher_hub.app_admins enable row level security;

revoke all on schema teacher_hub from anon, authenticated;
revoke all on all tables in schema teacher_hub from anon, authenticated;
revoke all on all sequences in schema teacher_hub from anon, authenticated;
revoke all on all routines in schema teacher_hub from anon, authenticated;

grant usage on schema teacher_hub to anon, authenticated;
grant select on teacher_hub.categories, teacher_hub.documents, teacher_hub.document_categories
  to anon, authenticated;
grant insert, update, delete on teacher_hub.categories, teacher_hub.documents, teacher_hub.document_categories
  to authenticated;
grant usage, select on all sequences in schema teacher_hub to authenticated;
grant execute on function teacher_hub.create_document(text, text, text, text, text, bigint, text[], bigint[])
  to anon, authenticated;
grant execute on function teacher_hub.is_admin() to anon, authenticated;

create policy "teacher_hub_categories_public_read"
on teacher_hub.categories for select to anon, authenticated
using (true);

create policy "teacher_hub_categories_admin_insert"
on teacher_hub.categories for insert to authenticated
with check (teacher_hub.is_admin());

create policy "teacher_hub_categories_admin_update"
on teacher_hub.categories for update to authenticated
using (teacher_hub.is_admin())
with check (teacher_hub.is_admin());

create policy "teacher_hub_categories_admin_delete"
on teacher_hub.categories for delete to authenticated
using (teacher_hub.is_admin());

create policy "teacher_hub_documents_public_read"
on teacher_hub.documents for select to anon, authenticated
using (deleted_at is null or teacher_hub.is_admin());

